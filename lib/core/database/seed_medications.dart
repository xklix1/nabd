/// Normalized Arabic text for robust search matching:
/// Removes Hamzas, turns 'ة' into 'ه', 'ى' into 'ي', removes diacritics.
String normalizeArabicText(String text) {
  return text
      .replaceAll(RegExp(r'[أإآا]'), 'ا')
      .replaceAll('ة', 'ه')
      .replaceAll('ى', 'ي')
      .replaceAll(RegExp(r'[\u064B-\u065F]'), '') // remove tashkeel
      .toLowerCase()
      .trim();
}

